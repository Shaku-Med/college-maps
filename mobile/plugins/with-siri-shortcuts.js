const fs = require('fs');
const path = require('path');
const { IOSConfig, withDangerousMod, withXcodeProject } = require('expo/config-plugins');

// Siri and the Shortcuts app: "Directions to 1N in CSI Map", "Take me to class with CSI Map", "Show my classes in
// CSI Map". Each one opens the app and leaves the request in UserDefaults, which src/lib/siri.ts picks up, so it
// also works when Siri starts the app cold. The places come from the same campus.json the map uses.

const FILE_NAME = 'CSIMapShortcuts.swift';
const CAMPUS_JSON = path.join(__dirname, '..', '..', 'app', 'campus', 'campus.json');
const HANDOFF_KEY = 'csimap.siriLink';
const MAX_SYNONYMS = 8;

// Safe inside a Swift string literal: no quotes, backslashes (which would start interpolation), or control
// characters can get through from the data file.
const swiftString = (value) => `"${String(value).replace(/[\\"]/g, '').replace(/[\u0000-\u001f\u007f]/g, '').trim()}"`;

function readPlaces() {
  const campus = JSON.parse(fs.readFileSync(CAMPUS_JSON, 'utf8'));
  return campus.places
    .filter((place) => /^[A-Za-z0-9]{1,10}$/.test(place.id) && typeof place.name === 'string')
    .map((place) => {
      const synonyms = [place.id, place.label, ...(place.keywords ?? [])]
        .filter((word) => typeof word === 'string' && word.trim() && word.toLowerCase() !== place.name.toLowerCase());
      return { id: place.id, name: place.name, synonyms: [...new Set(synonyms)].slice(0, MAX_SYNONYMS) };
    });
}

function swiftSource(places) {
  const cases = places.map((place) => `    case place${place.id} = ${swiftString(place.id)}`).join('\n');
  const names = places
    .map(
      (place) =>
        `        .place${place.id}: DisplayRepresentation(title: ${swiftString(place.name)}, subtitle: ${swiftString(place.id)}, image: nil, synonyms: [${place.synonyms.map(swiftString).join(', ')}]),`,
    )
    .join('\n');

  return `// Generated by plugins/with-siri-shortcuts.js from app/campus/campus.json on every prebuild. Do not edit.
import AppIntents
import Foundation

@available(iOS 16.0, *)
private func handToApp(_ path: String) {
    UserDefaults.standard.set(path, forKey: ${swiftString(HANDOFF_KEY)})
}

@available(iOS 16.0, *)
enum CampusPlace: String, AppEnum {
${cases}

    static let typeDisplayRepresentation: TypeDisplayRepresentation = "Campus place"
    static let caseDisplayRepresentations: [CampusPlace: DisplayRepresentation] = [
${names}
    ]
}

@available(iOS 16.0, *)
struct DirectionsToPlaceIntent: AppIntent {
    static let title: LocalizedStringResource = "Get directions"
    static let description = IntentDescription("Opens CSI Map with walking directions to a campus building, lot, or bus stop.")
    static let openAppWhenRun: Bool = true

    @Parameter(title: "Place")
    var place: CampusPlace

    @MainActor
    func perform() async throws -> some IntentResult {
        handToApp("directions/" + place.rawValue)
        return .result()
    }
}

@available(iOS 16.0, *)
struct DirectionsToNextClassIntent: AppIntent {
    static let title: LocalizedStringResource = "Directions to my next class"
    static let description = IntentDescription("Opens CSI Map with walking directions to your next class.")
    static let openAppWhenRun: Bool = true

    @MainActor
    func perform() async throws -> some IntentResult {
        handToApp("next-class")
        return .result()
    }
}

@available(iOS 16.0, *)
struct ShowClassesIntent: AppIntent {
    static let title: LocalizedStringResource = "Show my classes"
    static let description = IntentDescription("Opens your class schedule in CSI Map.")
    static let openAppWhenRun: Bool = true

    @MainActor
    func perform() async throws -> some IntentResult {
        handToApp("classes")
        return .result()
    }
}

@available(iOS 16.0, *)
struct CSIMapShortcuts: AppShortcutsProvider {
    static let shortcutTileColor: ShortcutTileColor = .blue

    static var appShortcuts: [AppShortcut] {
        AppShortcut(
            intent: DirectionsToPlaceIntent(),
            phrases: [
                "Directions to \\(\\.$place) in \\(.applicationName)",
                "Take me to \\(\\.$place) with \\(.applicationName)",
                "Get directions with \\(.applicationName)",
            ],
            shortTitle: "Directions",
            systemImageName: "figure.walk"
        )
        AppShortcut(
            intent: DirectionsToNextClassIntent(),
            phrases: [
                "Take me to class with \\(.applicationName)",
                "Directions to my next class in \\(.applicationName)",
            ],
            shortTitle: "Next class",
            systemImageName: "calendar.badge.clock"
        )
        AppShortcut(
            intent: ShowClassesIntent(),
            phrases: [
                "Show my classes in \\(.applicationName)",
                "Open my schedule in \\(.applicationName)",
            ],
            shortTitle: "My classes",
            systemImageName: "calendar"
        )
    }
}
`;
}

module.exports = function withSiriShortcuts(config) {
  config = withDangerousMod(config, [
    'ios',
    async (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const target = path.join(mod.modRequest.platformProjectRoot, projectName, FILE_NAME);
      fs.writeFileSync(target, swiftSource(readPlaces()));
      return mod;
    },
  ]);

  return withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${FILE_NAME}`;
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: mod.modResults });
    }
    return mod;
  });
};

// Exposed for a quick look at the generated Swift without a full prebuild.
module.exports.swiftSource = () => swiftSource(readPlaces());
